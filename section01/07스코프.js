// 스코프
// -> 전역(전체 영역) 스코프 / 지역 스코프
// -> 전역 스코프 : 전체 영역에서 접근 가능
// -> 지역 스코프 : 특정 영역에서만 접근 가능

let a =1; // 전역 스코프

function funcA(){ // 전역스코프를 선언했기 때문에 문제 없이 함수 호출이 가능함.
    let b =2; // 지역 스코프이기 때문에 밖에서는 호출할 수 없음.
    console.log(a); 
}

funcA();

// 대체적으로 블록 안에 선언된 변수들은 다 지역 스코프
// 함수 안의 함수도 밖에서 호출 불가능